"""Tests for jetstream.python_licenses, the python pack's license check of a repo's product dependencies."""

import importlib.metadata
import io
from collections.abc import Callable
from email.message import Message
from pathlib import Path
from typing import Final

import pytest

from jetstream import npm_licenses, python_licenses

CLASSIFIER: Final[str] = "License :: OSI Approved :: "
HEADER: Final[str] = "# This file was autogenerated by uv via the following command:\n#    uv export --frozen --no-dev --no-emit-project --no-hashes\n"


def metadata_of(fields: list[tuple[str, str]]) -> Message:
    """Return package metadata with ``fields``, in order."""
    metadata: Message = Message()
    for name, value in fields:
        metadata[name] = value
    return metadata


def installed(packages: dict[str, list[tuple[str, str]]]) -> Callable[[str], Message]:
    """Return a stand-in for importlib.metadata.metadata that knows only ``packages``, by name, each at version 1.0."""

    def metadata(name: str) -> Message:
        if name not in packages:
            raise importlib.metadata.PackageNotFoundError(name)
        return metadata_of([("Version", "1.0"), *packages[name]])

    return metadata


@pytest.mark.parametrize(
    ("fields", "license_id"),
    [
        ([("License-Expression", "MIT"), ("License", "GPL-3.0-only")], "MIT"),
        ([("License-Expression", "FSL-1.1-MIT")], "FSL-1.1-MIT"),
        ([("License", "BSD-3-Clause"), ("Classifier", f"{CLASSIFIER}BSD License")], "BSD-3-Clause"),
        ([("License", "ISC"), ("Classifier", f"{CLASSIFIER}BSD License")], "ISC"),
        ([("License", "Apache 2.0"), ("Classifier", f"{CLASSIFIER}Apache Software License")], "Apache-2.0"),
        ([("Classifier", f"{CLASSIFIER}MIT License"), ("Classifier", "Topic :: Utilities")], "MIT"),
        ([("Classifier", f"{CLASSIFIER}MIT License"), ("Classifier", f"{CLASSIFIER}Apache Software License")], "Apache-2.0 AND MIT"),
        ([("Classifier", f"{CLASSIFIER}MIT License"), ("Classifier", f"{CLASSIFIER}BSD License")], None),
        ([("Classifier", f"{CLASSIFIER}BSD License")], None),
        ([("License", "BSD")], None),
        ([("License", "3-Clause BSD License")], None),
        ([("License", "GPL-3.0-only")], None),
        ([], None),
    ],
)
def test_declared_reads_only_a_clear_license(fields: list[tuple[str, str]], license_id: str | None) -> None:
    """A License-Expression decides, then a License made of allowed SPDX IDs, then license classifiers if each names one license; anything else isn't clear."""
    assert python_licenses.declared(metadata_of(fields)) == license_id


@pytest.mark.parametrize("license_id", ["FSL-1.1-MIT", "BSD-4-Clause", "BSD-3-Clause-No-Nuclear-License", "BUSL-1.1", "GPL-3.0-only"])
def test_a_license_licensing_md_doesnt_allow_fails(license_id: str) -> None:
    """A license is compared by SPDX ID, so one with an allowed license's name in it fails."""
    export: str = HEADER + "a==1.0\n"
    found: list[str] = python_licenses.failures(["a"], export, {}, installed({"a": [("License-Expression", license_id)]}))
    assert found == [f"a 1.0: {license_id} isn't allowed in a direct product dependency"]


@pytest.mark.parametrize("license_id", ["MIT", "MIT-0", "PSF-2.0", "Apache-2.0 OR BSD-3-Clause"])
def test_an_allowed_license_passes(license_id: str) -> None:
    """A license licensing.md allows passes, in a direct dependency."""
    found: list[str] = python_licenses.failures(["a"], "a==1.0\n", {}, installed({"a": [("License-Expression", license_id)]}))
    assert found == []


def test_mpl_is_allowed_only_in_a_transitive_dependency() -> None:
    """MPL-2.0 is allowed when another package needs it, not as one of the repo's own dependencies (licensing.md)."""
    packages: Callable[[str], Message] = installed({"a": [("License-Expression", "MIT")], "b": [("License-Expression", "MPL-2.0")]})
    export: str = "a==1.0\nb==1.0\n    # via a\n"
    assert python_licenses.failures(["a"], export, {}, packages) == []
    assert python_licenses.failures(["b"], export, {}, packages) == ["b 1.0: MPL-2.0 isn't allowed in a direct product dependency"]


def test_names_are_compared_normalized() -> None:
    """A dependency's name matches the export's however it's written, so it's checked as a direct one."""
    packages: Callable[[str], Message] = installed({"foo-bar": [("License-Expression", "MPL-2.0")]})
    assert python_licenses.failures(["Foo_Bar[extra]>=1.0"], "foo-bar==1.0\n", {}, packages) == ["foo-bar 1.0: MPL-2.0 isn't allowed in a direct product dependency"]


def test_an_unclear_license_fails_until_its_reviewed() -> None:
    """A package whose metadata doesn't say clearly fails, and passes once python-licenses.toml records its license."""
    packages: Callable[[str], Message] = installed({"a": [("Classifier", f"{CLASSIFIER}BSD License")]})
    found: list[str] = python_licenses.failures(["a"], "a==1.0\n", {}, packages)
    assert found == ["a 1.0: its metadata doesn't say clearly which license it has: its license needs a review, in jetstream's python-licenses.toml"]
    assert python_licenses.failures(["a"], "a==1.0\n", {"a": "BSD-3-Clause"}, packages) == []


def test_a_reviewed_license_must_be_allowed() -> None:
    """A recorded license is checked like a declared one."""
    packages: Callable[[str], Message] = installed({"a": [("License", "BSD")]})
    found: list[str] = python_licenses.failures(["a"], "a==1.0\n", {"a": "MPL-2.0"}, packages)
    assert found == ["a 1.0: MPL-2.0 isn't allowed in a direct product dependency"]


def test_a_reviewed_package_that_declares_another_license_fails() -> None:
    """A recorded package that later says clearly that it has another license needs a review again; one that says the same passes."""
    export: str = "a==1.0\n"
    changed: Callable[[str], Message] = installed({"a": [("License-Expression", "BUSL-1.1")]})
    found: list[str] = python_licenses.failures(["a"], export, {"a": "BSD-3-Clause"}, changed)
    assert found == ["a 1.0: declares BUSL-1.1, but jetstream's python-licenses.toml records BSD-3-Clause: its license needs a review again"]
    same: Callable[[str], Message] = installed({"a": [("License-Expression", "BSD-3-Clause")]})
    assert python_licenses.failures(["a"], export, {"a": "BSD-3-Clause"}, same) == []


def test_a_package_that_isnt_installed_fails_unless_its_for_another_platform() -> None:
    """A package the export lists without a marker must be installed; one with a marker is for another platform when it isn't."""
    packages: Callable[[str], Message] = installed({})
    assert python_licenses.failures([], "a==1.0 ; sys_platform == 'emscripten'\n", {}, packages) == []
    assert python_licenses.failures([], "a==1.0\n", {}, packages) == ["a: isn't installed, so its license can't be read: run uv sync"]


def test_a_project_with_no_dependencies_passes() -> None:
    """An export with only uv's header has nothing to check."""
    assert python_licenses.failures([], HEADER, {}, installed({})) == []


@pytest.mark.parametrize(("package", "license_id"), sorted(python_licenses.load_reviewed().items()))
def test_every_reviewed_license_is_allowed(package: str, license_id: str) -> None:
    """Every license python-licenses.toml records is one licensing.md allows, at least in a transitive dependency, for a normalized name."""
    assert package == python_licenses.canonical(package)
    assert npm_licenses.allows(license_id, npm_licenses.ALLOWED_TRANSITIVE), f"{package}: {license_id}"


def test_requirement_name_rejects_a_line_that_isnt_a_requirement() -> None:
    """A line that doesn't start with a package name is an error, not skipped."""
    with pytest.raises(ValueError, match="not a requirement"):
        python_licenses.requirement_name("-e ./packages/a")


@pytest.mark.parametrize(("export", "status", "output"), [("tomlkit==0.15.2\n", 0, ""), ("yamllint==1.38.0\n", 1, "GPL-3.0-or-later isn't allowed in a transitive product dependency")])
def test_main_reads_the_export_and_the_installed_packages(tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str], export: str, status: int, output: str) -> None:
    """The command reads the export from standard input and each license from the installed package (here, jetstream's own .venv), printing each failure."""
    pyproject: Path = tmp_path / "pyproject.toml"
    pyproject.write_text('[project]\nname = "a"\ndependencies = ["tomlkit==0.15.2"]\n')
    monkeypatch.setattr("sys.stdin", io.StringIO(HEADER + export))
    assert python_licenses.main([str(pyproject)]) == status
    assert output in capsys.readouterr().out
