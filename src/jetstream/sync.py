"""What jetstream writes into a repo, and how ``jetstream sync`` and ``jetstream check`` use it.

From the packs in a repo's ``[tool.jetstream] packs``, ``expected()`` works out
everything jetstream owns in that repo (decision 6):

- **owned files**: each pack's ``files/<pack>/``, copied as-is, and the files
  generated from each pack's ``parts/<pack>/`` (``.pre-commit-config.yaml``);
- **the .gitignore block** between ``# >>> jetstream`` and ``# <<< jetstream``,
  from each pack's ``parts/<pack>/gitignore``;
- **jetstream's pyproject.toml keys** (decision 7), from each pack's
  ``parts/<pack>/pyproject.toml``. Every other key belongs to the repo.

``sync()`` writes them, and ``check()`` lists how the repo differs from them.
Neither touches anything else, such as the jetstream pin.
"""

from __future__ import annotations

import subprocess
import tomllib
from dataclasses import dataclass
from importlib.resources import files
from importlib.resources.abc import Traversable
from pathlib import Path
from typing import Any, Final

import tomlkit
import tomlkit.items

# Every pack, in the order their parts are combined. core is required.
PACKS: Final[tuple[str, ...]] = ("core", "python", "website")

GITIGNORE_START: Final[str] = "# >>> jetstream: written by `jetstream sync`; the repo's own lines go outside this block"
GITIGNORE_END: Final[str] = "# <<< jetstream"

# A release deletes its generated workflows by not shipping them, so check
# fails on any file with this prefix the release doesn't write (decision 6).
WORKFLOWS_DIR: Final[str] = ".github/workflows"
WORKFLOW_PREFIX: Final[str] = "jetstream-"

# A file in parts/<pack>/ and the owned file generated by combining it across packs.
GENERATED_FILES: Final[dict[str, str]] = {
    "pre-commit-config.yaml": ".pre-commit-config.yaml",
}

PACKAGE: Final[Traversable] = files("jetstream")

type KeyPath = tuple[str, ...]


class SyncError(Exception):
    """A problem with the repo's setup, reported in one line."""


@dataclass(frozen=True)
class Owned:
    """One owned file's expected content."""

    content: bytes
    executable: bool


@dataclass(frozen=True)
class Expected:
    """Everything jetstream owns in a repo with these packs."""

    packs: tuple[str, ...]
    files: dict[str, Owned]  # repo-relative path -> content
    gitignore_block: str  # from GITIGNORE_START to GITIGNORE_END, with a final newline
    pyproject_keys: dict[KeyPath, Any]  # (table, ..., key) -> value


def repo_root(start: Path | None = None) -> Path:
    """Return the root of the git repo containing ``start`` (default: the current directory)."""
    result: subprocess.CompletedProcess[str] = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],  # noqa: S607
        cwd=start,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise SyncError("not in a git repo")
    return Path(result.stdout.strip())


def read_packs(root: Path) -> tuple[str, ...]:
    """Return the packs in ``root``'s ``[tool.jetstream] packs``, in PACKS order."""
    pyproject: Path = root / "pyproject.toml"
    try:
        config: dict[str, Any] = tomllib.loads(pyproject.read_text())
    except FileNotFoundError as e:
        raise SyncError(f"no pyproject.toml in {root}") from e
    except tomllib.TOMLDecodeError as e:
        raise SyncError(f"can't parse pyproject.toml: {e}") from e

    packs: object = config.get("tool", {}).get("jetstream", {}).get("packs")
    if not isinstance(packs, list) or not all(isinstance(pack, str) for pack in packs):
        raise SyncError('pyproject.toml needs [tool.jetstream] packs, a list such as ["core"]')
    unknown: list[str] = [pack for pack in packs if pack not in PACKS]
    if unknown:
        raise SyncError(f"unknown pack(s) in [tool.jetstream] packs: {', '.join(unknown)}; packs are {', '.join(PACKS)}")
    if "core" not in packs:
        raise SyncError('[tool.jetstream] packs must include "core"')
    return tuple(pack for pack in PACKS if pack in packs)


def walk(directory: Traversable, prefix: str = "") -> dict[str, Traversable]:
    """Return every file under ``directory``, by its path relative to it."""
    found: dict[str, Traversable] = {}
    if not directory.is_dir():
        return found
    for entry in directory.iterdir():
        if entry.name == "__pycache__":
            continue
        path: str = f"{prefix}{entry.name}"
        if entry.is_dir():
            found.update(walk(entry, f"{path}/"))
        else:
            found[path] = entry
    return found


def is_executable(entry: Traversable) -> bool:
    """Return whether a package file is executable (only checkable when it's a real file)."""
    return isinstance(entry, Path) and bool(entry.stat().st_mode & 0o111)


def flatten(table: dict[str, Any], prefix: KeyPath = ()) -> dict[KeyPath, Any]:
    """Return the leaf keys of a parsed TOML ``table``, by their path."""
    leaves: dict[KeyPath, Any] = {}
    for key, value in table.items():
        path: KeyPath = (*prefix, key)
        if isinstance(value, dict):
            leaves.update(flatten(value, path))
        else:
            leaves[path] = value
    return leaves


def expected(packs: tuple[str, ...]) -> Expected:
    """Return everything jetstream owns in a repo with ``packs``."""
    owned: dict[str, Owned] = {}
    generated: dict[str, list[str]] = {name: [] for name in GENERATED_FILES}
    gitignore: list[str] = []
    pyproject_keys: dict[KeyPath, Any] = {}

    for pack in packs:
        for path, entry in walk(PACKAGE / "files" / pack).items():
            if path in owned:
                raise SyncError(f"packs both write {path}")  # a bug in jetstream, caught by its tests
            owned[path] = Owned(entry.read_bytes(), is_executable(entry))

        parts: Traversable = PACKAGE / "parts" / pack
        for part in GENERATED_FILES:
            if (parts / part).is_file():
                generated[part].append((parts / part).read_text())
        if (parts / "gitignore").is_file():
            gitignore.append((parts / "gitignore").read_text())
        if (parts / "pyproject.toml").is_file():
            pyproject_keys.update(flatten(tomllib.loads((parts / "pyproject.toml").read_text())))

    for part, texts in generated.items():
        if texts:
            owned[GENERATED_FILES[part]] = Owned("\n".join(texts).encode(), executable=False)

    block: str = "\n".join([GITIGNORE_START, *(text.rstrip("\n") for text in gitignore), GITIGNORE_END]) + "\n"
    return Expected(packs, owned, block, pyproject_keys)


# --- .gitignore


def split_gitignore(text: str) -> tuple[str, str | None, str]:
    """Split a .gitignore into (before, jetstream's block or None, after)."""
    lines: list[str] = text.splitlines(keepends=True)
    starts: list[int] = [i for i, line in enumerate(lines) if line.startswith("# >>> jetstream")]
    ends: list[int] = [i for i, line in enumerate(lines) if line.rstrip("\n") == GITIGNORE_END]
    if not starts and not ends:
        return text, None, ""
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise SyncError(f".gitignore needs exactly one '# >>> jetstream' line followed by one '{GITIGNORE_END}' line")
    block: str = "".join(lines[starts[0] : ends[0] + 1])
    if not block.endswith("\n"):
        block += "\n"
    return "".join(lines[: starts[0]]), block, "".join(lines[ends[0] + 1 :])


def synced_gitignore(text: str, block: str) -> str:
    """Return ``text`` with jetstream's block replaced by ``block``, or ``block`` added first."""
    before: str
    current: str | None
    after: str
    before, current, after = split_gitignore(text)
    if current is None:
        return block + ("\n" + text if text else "")
    return before + block + after


# --- pyproject.toml


def unwrap(value: Any) -> Any:  # noqa: ANN401 (TOML values)
    """Return a tomlkit value as plain Python, for comparison."""
    return value.unwrap() if isinstance(value, tomlkit.items.Item) else value


def get_key(document: tomlkit.TOMLDocument, path: KeyPath) -> tuple[bool, Any]:
    """Return (whether ``path`` is set in ``document``, its value)."""
    node: Any = document
    for key in path:
        if not hasattr(node, "keys") or key not in node:
            return False, None
        node = node[key]
    return True, unwrap(node)


def set_key(document: tomlkit.TOMLDocument, path: KeyPath, value: Any) -> None:  # noqa: ANN401
    """Set ``path`` in ``document`` to ``value``, adding tables as needed and keeping the rest as it is."""
    node: Any = document
    for depth, key in enumerate(path[:-1]):
        if key not in node:
            # A table with only sub-tables ([tool]) is a super table, so no empty header is written.
            node[key] = tomlkit.table(is_super_table=depth < len(path) - 2)
        node = node[key]
    item: Any = tomlkit.item(value)
    if isinstance(item, tomlkit.items.Array) and len(value) > 1:
        item.multiline(True)
    node[path[-1]] = item


def format_key(path: KeyPath) -> str:
    """Return ``path`` as it reads in pyproject.toml: ``[tool.uv] exclude-newer``."""
    return f"[{'.'.join(path[:-1])}] {path[-1]}" if len(path) > 1 else path[0]


# --- sync and check


def differences(root: Path, want: Expected) -> list[str]:
    """Return a line for each way the repo at ``root`` differs from ``want``."""
    found: list[str] = []
    for path, owned in sorted(want.files.items()):
        target: Path = root / path
        if not target.is_file():
            found.append(f"{path} is missing")
        elif target.read_bytes() != owned.content:
            found.append(f"{path} differs from what jetstream writes")
        elif owned.executable and not target.stat().st_mode & 0o111:
            found.append(f"{path} isn't executable")

    workflows: Path = root / WORKFLOWS_DIR
    if workflows.is_dir():
        for workflow in sorted(workflows.glob(f"{WORKFLOW_PREFIX}*")):
            path: str = f"{WORKFLOWS_DIR}/{workflow.name}"
            if path not in want.files:
                found.append(f"{path} isn't a workflow this jetstream release writes")

    gitignore: Path = root / ".gitignore"
    current: str | None = split_gitignore(gitignore.read_text())[1] if gitignore.is_file() else None
    if current is None:
        found.append(".gitignore has no jetstream block")
    elif current != want.gitignore_block:
        found.append(".gitignore's jetstream block differs from what jetstream writes")

    document: tomlkit.TOMLDocument = tomlkit.parse((root / "pyproject.toml").read_text())
    for key_path, value in want.pyproject_keys.items():
        present: bool
        actual: Any
        present, actual = get_key(document, key_path)
        if not present:
            found.append(f"pyproject.toml: {format_key(key_path)} is missing; jetstream sets {tomlkit.item(value).as_string()}")
        elif actual != value:
            found.append(
                f"pyproject.toml: {format_key(key_path)} is {tomlkit.item(actual).as_string()}; "
                f"jetstream sets {tomlkit.item(value).as_string()}",
            )
    return found


def sync(root: Path) -> list[str]:
    """Write everything jetstream owns into the repo at ``root``; return what changed."""
    want: Expected = expected(read_packs(root))
    changed: list[str] = []

    for path, owned in sorted(want.files.items()):
        target: Path = root / path
        if not target.is_file() or target.read_bytes() != owned.content:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(owned.content)
            changed.append(path)
        if owned.executable and not target.stat().st_mode & 0o111:
            target.chmod(target.stat().st_mode | 0o111)
            if path not in changed:
                changed.append(path)

    workflows: Path = root / WORKFLOWS_DIR
    if workflows.is_dir():
        for workflow in sorted(workflows.glob(f"{WORKFLOW_PREFIX}*")):
            path: str = f"{WORKFLOWS_DIR}/{workflow.name}"
            if path not in want.files:
                workflow.unlink()
                changed.append(f"{path} (deleted)")

    gitignore: Path = root / ".gitignore"
    text: str = gitignore.read_text() if gitignore.is_file() else ""
    updated: str = synced_gitignore(text, want.gitignore_block)
    if updated != text:
        gitignore.write_text(updated)
        changed.append(".gitignore")

    pyproject: Path = root / "pyproject.toml"
    original: str = pyproject.read_text()
    document: tomlkit.TOMLDocument = tomlkit.parse(original)
    for key_path, value in want.pyproject_keys.items():
        present: bool
        actual: Any
        present, actual = get_key(document, key_path)
        if not present or actual != value:
            set_key(document, key_path, value)
    if tomlkit.dumps(document) != original:
        pyproject.write_text(tomlkit.dumps(document))
        changed.append("pyproject.toml")
    return changed


def check(root: Path) -> list[str]:
    """Return a line for each way the repo at ``root`` differs from what ``sync`` would write."""
    return differences(root, expected(read_packs(root)))
